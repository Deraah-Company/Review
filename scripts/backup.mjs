import {DatabaseSync} from 'node:sqlite';
import {mkdirSync,cpSync,existsSync} from 'node:fs';
import path from 'node:path';
const data=path.resolve(process.env.DATA_DIR||'data');
const destination=path.join(data,'backups',new Date().toISOString().replace(/[:.]/g,'-'));
mkdirSync(destination,{recursive:true});
const database=new DatabaseSync(path.join(data,'academy.sqlite'));
database.exec("VACUUM INTO '"+path.join(destination,'academy.sqlite').replaceAll("'","''")+"'");database.close();
if(existsSync(path.join(data,'uploads')))cpSync(path.join(data,'uploads'),path.join(destination,'uploads'),{recursive:true});
console.log('Backup created: '+destination);
